def validate_tasks(tasks):
    if not isinstance(tasks, list):
        raise APIError(400, "A lista de tarefas é inválida.")
    if len(tasks) > MAX_TASKS:
        raise APIError(413, f"O quadro pode ter no máximo {MAX_TASKS} tarefas.")

    validated = []
    for task in tasks:
        if not isinstance(task, dict):
            raise APIError(400, "Uma tarefa está em formato inválido.")
        task_id = task.get("id")
        title = task.get("title")
        description = task.get("desc")
        status = task.get("status")
        created_at = task.get("createdAt")
        subtasks = task.get("subtasks", [])
        if not isinstance(task_id, str) or not task_id or len(task_id) > 80:
            raise APIError(400, "Uma tarefa tem um identificador inválido.")
        if not isinstance(title, str) or not title.strip() or len(title) > 80:
            raise APIError(400, "O título de uma tarefa é inválido.")
        if not isinstance(description, str) or len(description) > 400:
            raise APIError(400, "A descrição de uma tarefa é inválida.")
        if not isinstance(status, str) or status not in {"todo", "doing", "done"}:
            raise APIError(400, "O status de uma tarefa é inválido.")
        if (
            isinstance(created_at, bool) or
            not isinstance(created_at, (int, float)) or
            not math.isfinite(created_at)
        ):
            raise APIError(400, "A data de uma tarefa é inválida.")
        if not isinstance(subtasks, list) or len(subtasks) > MAX_SUBTASKS:
            raise APIError(400, "O checklist de uma tarefa é inválido.")
        safe_subtasks = []
        for item in subtasks:
            if (
                not isinstance(item, dict) or
                not isinstance(item.get("id"), str) or
                not item["id"] or
                len(item["id"]) > 80 or
                not isinstance(item.get("title"), str) or
                not item["title"].strip() or
                len(item["title"]) > 160 or
                not isinstance(item.get("done"), bool)
            ):
                raise APIError(400, "Um item do checklist é inválido.")
            safe_subtasks.append({
                "id": item["id"],
                "title": item["title"].strip(),
                "done": item["done"]
            })
        validated.append({
            "id": task_id,
            "title": title.strip(),
            "desc": description,
            "status": status,
            "createdAt": created_at,
            "subtasks": safe_subtasks
        })
    return validated


def board_tasks(uid):
    def select(connection):
        row = connection.execute(
            "SELECT tasks FROM boards WHERE user_id = %s",
            (uid,)
        ).fetchone()
        if row is None:
            connection.execute(
                "INSERT INTO boards (user_id, tasks) VALUES (%s, %s) ON CONFLICT (user_id) DO NOTHING",
                (uid, Jsonb([]))
            )
            return []
        tasks = row["tasks"]
        if not isinstance(tasks, list):
            raise APIError(500, "As tarefas do quadro estão em um formato inválido.")
        if len(tasks) > MAX_TASKS:
            raise APIError(413, "O quadro tem tarefas demais para uma única consulta à IA.")
        return tasks

    return database_call(select)


def save_board_tasks(uid, tasks):
    def save(connection):
        connection.execute(
            """
            INSERT INTO boards (user_id, tasks) VALUES (%s, %s)
            ON CONFLICT (user_id)
            DO UPDATE SET tasks = EXCLUDED.tasks, updated_at = now()
            """,
            (uid, Jsonb(tasks))
        )

    database_call(save)


