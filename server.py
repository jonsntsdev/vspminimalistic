def ensure_schema(connection):
    global SCHEMA_READY
    if SCHEMA_READY:
        return
    with SCHEMA_LOCK:
        if SCHEMA_READY:
            return
        for statement in SCHEMA_SQL:
            connection.execute(statement)
        connection.commit()
        SCHEMA_READY = True


def database_call(operation):
    database_url = os.environ.get("DATABASE_URL", "").strip()
    if not database_url:
        raise APIError(503, "Configure DATABASE_URL com a URL interna do PostgreSQL no Render.")
    try:
        with psycopg.connect(
            database_url,
            connect_timeout=8,
            row_factory=dict_row
        ) as connection:
            ensure_schema(connection)
            return operation(connection)
    except APIError:
        raise
    except psycopg.Error:
        current_app.logger.exception("PostgreSQL request failed.")
        raise APIError(503, "Não foi possível acessar o banco PostgreSQL. Confira DATABASE_URL no Render.") from None


def create_user(email, password_hash):
    def insert(connection):
        try:
            user = connection.execute(
                "INSERT INTO app_users (email, password_hash) VALUES (%s, %s) RETURNING id, email",
                (email, password_hash)
            ).fetchone()
        except psycopg.errors.UniqueViolation:
            raise APIError(409, "Este e-mail já possui uma conta. Entre com sua senha.") from None
        connection.execute(
            "INSERT INTO boards (user_id, tasks) VALUES (%s, %s)",
            (user["id"], Jsonb([]))
        )
        return {"id": user["id"], "email": user["email"]}

    return database_call(insert)


def find_user(email):
    def select(connection):
        return connection.execute(
            "SELECT id, email, password_hash FROM app_users WHERE email = %s",
            (email,)
        ).fetchone()

    return database_call(select)


def authenticated_uid():
    user_id = session.get("user_id")
    if not isinstance(user_id, int):
        raise APIError(401, "Entre na sua conta para continuar.")
    return user_id


def request_payload():
    payload = request.get_json(silent=True)
    if not isinstance(payload, dict):
        raise APIError(400, "Envie uma solicitação JSON válida.")
    return payload


def normalize_credentials(payload):
    email = payload.get("email")
    password = payload.get("password")
    if not isinstance(email, str):
        raise APIError(400, "Informe um endereço de e-mail válido.")
    email = email.strip().lower()
    if (
        len(email) > MAX_EMAIL_LENGTH or
        not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email)
    ):
        raise APIError(400, "Informe um endereço de e-mail válido.")
    if not isinstance(password, str) or not 8 <= len(password) <= MAX_PASSWORD_LENGTH:
        raise APIError(400, f"A senha deve ter entre 8 e {MAX_PASSWORD_LENGTH} caracteres.")
    return email, password


def check_rate_limit(key, limit=REQUESTS_PER_MINUTE, window_seconds=60):
    now = time.monotonic()
    with RATE_LIMIT_LOCK:
        recent = [stamp for stamp in RATE_LIMITS.get(key, []) if now - stamp < window_seconds]
        if len(recent) >= limit:
            RATE_LIMITS[key] = recent
            return False
        recent.append(now)
        RATE_LIMITS[key] = recent
        if len(RATE_LIMITS) > 2000:
            for user_key, stamps in list(RATE_LIMITS.items()):
                if not any(now - stamp < 60 for stamp in stamps):
                    RATE_LIMITS.pop(user_key, None)
    return True


def check_auth_rate_limit():
    address = request.remote_addr or "unknown"
    if not check_rate_limit(f"auth:{address}", AUTH_REQUESTS_PER_MINUTE, 60):
        raise APIError(429, "Muitas tentativas. Aguarde um minuto e tente novamente.")


def set_user_session(user):
    session.clear()
    session.permanent = True
    session["user_id"] = user["id"]
    session["email"] = user["email"]


@app.post("/api/auth/register")
def register():
    check_auth_rate_limit()
    email, password = normalize_credentials(request_payload())
    password_hash = generate_password_hash(password)
    user = create_user(email, password_hash)
    set_user_session(user)
    return jsonify(user={"id": user["id"], "email": user["email"]}), 201


@app.post("/api/auth/login")
def login():
    check_auth_rate_limit()
    email, password = normalize_credentials(request_payload())
    user = find_user(email)
    if not user or not check_password_hash(user["password_hash"], password):
        raise APIError(401, "E-mail ou senha incorretos.")
    set_user_session(user)
    return jsonify(user={"id": user["id"], "email": user["email"]})


